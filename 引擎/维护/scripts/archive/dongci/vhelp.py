"""动词变化形式轮（2026-11）的写法模板。组合列（N）讲清每种形式的作用和它带来的意思，音变列（P）讲清这个形式是怎么变成今天的样子的。
步骤行以“# ”开头的，写表时按先后自动编成 ①②③（过去式、过去分词这些“功能”步骤）；“→ ”开头的是意思再往下变的步骤。"""

PRESENT = '说这件事在过去发生、已经结束了'


def PT(res, how=''):
    """过去式：动作发生在过去"""
    return f'# 过去式：{PRESENT}{how} → {res}'


def PPT(v, res=None, note=''):
    """及物动词的过去分词：完成 + 被动"""
    return f'# 过去分词：有“完成”“被动”两层意思——跟在 have 后面是“已经{v}了”，跟在 be 后面是“被{v}”{note} → {res or f"已经{v}了；被{v}"}'


def PPI(v, base, res=None):
    """不及物动词的过去分词：只有“完成”"""
    return f'# 过去分词：跟在 have 后面说“已经{v}了”；{base} 后面不带宾语，过去分词就没有“被…”的意思 → {res or f"已经{v}了"}'


def AT(v, res, how=''):
    """及物动词的过去分词当形容词：被…了的"""
    return f'→ 过去分词放在名词前、be 后面当形容词，就是“被{v}了的”{how} → {res}'


def AI(v, res, how=''):
    """不及物动词的过去分词当形容词：已经…了的"""
    return f'→ 过去分词当形容词，说“已经{v}了”的状态{how} → {res}'


